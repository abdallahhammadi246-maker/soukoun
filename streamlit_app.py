import streamlit as st

st.set_page_config(page_title="منصة سُكون", page_icon="🧠", layout="centered")

# اتجاه الكتابة من اليمين لليسار
st.markdown(
    """
    <style>
    .stApp, .stMarkdown, label, p, h1, h2, h3 { direction: rtl; text-align: right; }
    </style>
    """,
    unsafe_allow_html=True,
)

DISCLAIMER = "⚠️ هذه أداة توعوية سريعة وليست تشخيصاً طبياً ولا بديلاً عن استشارة مختص."

HELP_NOTE = (
    "💬 إذا كانت عندك أفكار لإيذاء نفسك، لا تبقى وحدك: كلّم شخصاً تثق فيه "
    "(فرد من العائلة أو صديق) أو اتصل بالطوارئ أو توجه لأقرب مصلحة استعجالات."
)

st.title("🧠 منصة سُكون للتقييم والدعم النفسي")
st.caption("أدوات سريعة وتمارين تفاعلية موجهة للطلبة والمختصين.")
st.warning(DISCLAIMER)

tab1, tab2, tab3 = st.tabs(["📝 اختبار المزاج", "📚 قلق الامتحان", "🌬️ تمرين التنفس"])

# ---------- 1. اختبار المزاج ----------
with tab1:
    st.subheader("اختر الإجابة التي تصف شعورك خلال الأسبوع الماضي")

    q1 = st.radio(
        "1. الحزن والشعور بالضيق",
        [
            "0 - لا أشعر بالحزن.",
            "1 - أشعر بالحزن معظم الوقت.",
            "2 - أنا حزين طوال الوقت.",
            "3 - أنا حزين بدرجة لا أستطيع تحملها.",
        ],
        key="q1",
    )
    q2 = st.radio(
        "2. النظرة للمستقبل",
        [
            "0 - لست محبطاً بشأن مستقبلي.",
            "1 - أشعر بالإحباط بشأن مستقبلي أكثر من السابق.",
            "2 - لا أتوقع أن تسير الأمور على ما يرام.",
            "3 - أشعر أن مستقبلي ميؤوس منه.",
        ],
        key="q2",
    )
    q3 = st.radio(
        "3. الشعور بالفشل",
        [
            "0 - لا أشعر بالفشل.",
            "1 - أشعر أنني فشلت أكثر من الشخص العادي.",
            "2 - عندما أنظر إلى الوراء، أرى الكثير من الفشل.",
            "3 - أشعر أنني فاشل تماماً.",
        ],
        key="q3",
    )

    if st.button("احسب النتيجة", type="primary", key="btn_mood"):
        score = int(q1[0]) + int(q2[0]) + int(q3[0])
        st.markdown(f"### المجموع: {score} من 9")

        if score <= 3:
            st.success("🟢 المستوى: منخفض / طبيعي. أمورك طيبة، واصل الاهتمام بصحتك النفسية وبنشاطاتك اليومية.")
        elif score <= 6:
            st.warning(
                "🟡 المستوى: متوسط. تحتاج شوية راحة. جرب تمارين التنفس، نظّم وقتك، "
                "وتكلم مع شخص قريب منك على اللي تحس بيه."
            )
        else:
            st.error(
                "🔴 المستوى: مرتفع. اللي تحس بيه مهم وما تعيش فيه وحدك. "
                "نصيحتنا تتكلم مع شخص تثق فيه، وتستشير أخصائي نفسي أو طبيب."
            )

        if int(q3[0]) == 3 or score >= 7:
            st.info(HELP_NOTE)

        st.caption(DISCLAIMER)

# ---------- 2. قلق الامتحان ----------
with tab2:
    st.subheader("اختر الإجابة الأقرب لحالتك")
    options = ["1 - أبداً", "2 - أحياناً", "3 - غالباً", "4 - دائماً"]

    t1 = st.radio("1. هل تشعر بتسارع ضربات القلب قبل أو أثناء الامتحان؟", options, key="t1")
    t2 = st.radio("2. هل تخاف أن تنسى المعلومات أثناء الإجابة؟", options, key="t2")

    if st.button("احسب قلق الامتحان", type="primary", key="btn_tai"):
        score = int(t1[0]) + int(t2[0])
        st.markdown(f"### المجموع: {score} من 8")

        if score <= 3:
            st.success("🟢 القلق الامتحاني: منخفض. أنت في حالة تركيز جيدة، استمر هكذا.")
        elif score <= 5:
            st.warning("🟡 القلق الامتحاني: متوسط. حاول تنظيم وقت المراجعة وخذ فترات راحة منتظمة.")
        else:
            st.error(
                "🔴 القلق الامتحاني: مرتفع. جرب التنفس العميق، وقسّم المواد على أيام "
                "باش يخف الضغط. وإذا استمر، تكلم مع مرشد أو مختص."
            )

        st.caption(DISCLAIMER)

# ---------- 3. تمرين التنفس ----------
with tab3:
    st.subheader("🌬️ تمرين التنفس المقود (4-4-8)")
    st.markdown(
        """
1. **شهيق:** خذ نفساً عميقاً من الأنف لمدة **4 ثوانٍ**.
2. **حبس النفس:** احبس الهواء لمدة **4 ثوانٍ**.
3. **زفير:** أخرج الهواء ببطء من الفم لمدة **8 ثوانٍ**.

🔁 كرر العملية **5 إلى 10 مرات** وركز على نفَسك فقط.
"""
    )
